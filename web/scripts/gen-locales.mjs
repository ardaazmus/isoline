// Scans messages/*.json and writes src/i18n/generated.ts.
// Dropping a new xx.json (or xx-YY.json) file into messages/ adds a language: no code change needed.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "messages");
const out = join(root, "src", "i18n", "generated.ts");

const files = readdirSync(dir)
  .filter((f) => /^[a-z]{2}(-[A-Z]{2})?\.json$/.test(f))
  .sort();

if (!files.includes("tr.json")) {
  throw new Error("messages/tr.json is the default language and must exist");
}

const entries = files.map((file) => {
  const code = file.replace(/\.json$/, "");
  const json = JSON.parse(readFileSync(join(dir, file), "utf8"));
  const meta = json._meta ?? {};
  if (!meta.nativeName) {
    throw new Error(`messages/${file}: _meta.nativeName is required`);
  }
  return {
    code,
    ident: "m_" + code.replace("-", "_"),
    nativeName: meta.nativeName,
    dir: meta.dir === "rtl" ? "rtl" : "ltr",
    intl: meta.intl ?? code,
  };
});

const lines = [
  "// AUTO-GENERATED by scripts/gen-locales.mjs. Do not edit.",
  ...entries.map((e) => `import ${e.ident} from "../../messages/${e.code}.json";`),
  "",
  "export const LOCALES = [",
  ...entries.map(
    (e) =>
      `  { code: ${JSON.stringify(e.code)}, nativeName: ${JSON.stringify(e.nativeName)}, dir: ${JSON.stringify(e.dir)}, intl: ${JSON.stringify(e.intl)} },`,
  ),
  "] as const;",
  "",
  "export const MESSAGES: Record<string, unknown> = {",
  ...entries.map((e) => `  ${JSON.stringify(e.code)}: ${e.ident},`),
  "};",
  "",
];

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`i18n: ${entries.map((e) => e.code).join(", ")}`);

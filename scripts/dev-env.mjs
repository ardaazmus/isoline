#!/usr/bin/env node
// Writes the local development secrets once: ./.env (Docker Compose), web/.env.local (Next.js, worker, tests) and
// deploy/seaweedfs/s3.json (storage identities). Existing files are kept unless --force is given, so a running
// database keeps its passwords. Nothing here is committed (.gitignore covers .env*, s3.json is ignored too).
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const force = process.argv.includes("--force");
const secret = (n = 24) => randomBytes(n).toString("base64url");

const ports = { PG_PORT: "5545", S3_PORT: "8333", MAIL_SMTP_PORT: "1125", MAIL_UI_PORT: "8125", CLAMAV_PORT: "3310" };
const s = {
  PG_SUPERUSER_PASSWORD: secret(),
  OWNER_PASSWORD: secret(),
  APP_PASSWORD: secret(),
  SYSTEM_PASSWORD: secret(),
  S3_ACCESS_KEY: `isoline${secret(6)}`,
  S3_SECRET_KEY: secret(30),
  AUTH_SECRET: secret(48),
};

function write(file, content) {
  const path = join(root, file);
  if (existsSync(path) && !force) {
    console.log(`kept ${file} (use --force to regenerate)`);
    return false;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${file}`);
  return true;
}

const url = (user, pw, db) => `postgres://${user}:${pw}@127.0.0.1:${ports.PG_PORT}/${db}`;

const wroteRoot = write(
  ".env",
  Object.entries({ ...ports, PG_SUPERUSER_PASSWORD: s.PG_SUPERUSER_PASSWORD, CLOUDFLARE_TUNNEL_TOKEN: "" })
    .map(([k, v]) => `${k}=${v}`)
    .join("\n") + "\n",
);
// secrets that do not depend on the database passwords; added to an existing web/.env.local when missing
const independent = { APP_ENCRYPTION_KEY: randomBytes(32).toString("base64url") };

if (!wroteRoot && !force) {
  const local = join(root, "web/.env.local");
  if (existsSync(local)) {
    const text = readFileSync(local, "utf8");
    const missing = Object.entries(independent).filter(([k]) => !new RegExp(`^${k}=`, "m").test(text));
    if (missing.length) {
      appendFileSync(local, (text.endsWith("\n") ? "" : "\n") + missing.map(([k, v]) => `${k}=${v}`).join("\n") + "\n");
      console.log(`added ${missing.map(([k]) => k).join(", ")} to web/.env.local`);
    }
  }
  console.log("Root .env exists: web/.env.local and s3.json are left as they are so the passwords stay in sync.");
  process.exit(0);
}

write(
  "web/.env.local",
  [
    "# Generated by scripts/dev-env.mjs — local development only.",
    `DATABASE_ADMIN_URL=${url("postgres", s.PG_SUPERUSER_PASSWORD, "postgres")}`,
    `DATABASE_OWNER_URL=${url("isoline_owner", s.OWNER_PASSWORD, "isoline")}`,
    `DATABASE_URL=${url("isoline_app", s.APP_PASSWORD, "isoline")}`,
    `DATABASE_SYSTEM_URL=${url("isoline_system", s.SYSTEM_PASSWORD, "isoline")}`,
    `DB_OWNER_PASSWORD=${s.OWNER_PASSWORD}`,
    `DB_APP_PASSWORD=${s.APP_PASSWORD}`,
    `DB_SYSTEM_PASSWORD=${s.SYSTEM_PASSWORD}`,
    `BETTER_AUTH_SECRET=${s.AUTH_SECRET}`,
    "BETTER_AUTH_URL=http://localhost:3210",
    "APP_BASE_URL=http://localhost:3210",
    `S3_ENDPOINT=http://127.0.0.1:${ports.S3_PORT}`,
    "S3_REGION=us-east-1",
    "S3_BUCKET=isoline-evidence",
    `S3_ACCESS_KEY=${s.S3_ACCESS_KEY}`,
    `S3_SECRET_KEY=${s.S3_SECRET_KEY}`,
    "EMAIL_SMTP_HOST=127.0.0.1",
    `EMAIL_SMTP_PORT=${ports.MAIL_SMTP_PORT}`,
    "EMAIL_FROM=Isoline <no-reply@isoline.local>",
    `MAIL_API_URL=http://127.0.0.1:${ports.MAIL_UI_PORT}`,
    `CLAMAV_HOST=127.0.0.1`,
    `CLAMAV_PORT=${ports.CLAMAV_PORT}`,
    "SCANNER=dev",
    "OIDC_ISSUER=",
    "OIDC_CLIENT_ID=",
    "OIDC_CLIENT_SECRET=",
    ...Object.entries(independent).map(([k, v]) => `${k}=${v}`),
    "",
  ].join("\n"),
);

write(
  "deploy/seaweedfs/s3.json",
  JSON.stringify(
    { identities: [{ name: "isoline", credentials: [{ accessKey: s.S3_ACCESS_KEY, secretKey: s.S3_SECRET_KEY }], actions: ["Read", "Write", "List", "Tagging", "Admin"] }] },
    null,
    2,
  ) + "\n",
);
